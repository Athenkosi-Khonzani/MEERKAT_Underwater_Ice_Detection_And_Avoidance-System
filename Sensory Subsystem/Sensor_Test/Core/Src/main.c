void Calibrate_Sensor(I2C_HandleTypeDef *hi2c, uint16_t exact_target_distance_mm)
{
    uint32_t total_distance = 0;
    uint8_t valid_samples = 0;



    // Assuming you have a way to write to line 2, or just wait:
    HAL_Delay(3000); // Give yourself 3 seconds to place an object exactly 100mm away



    // Take 20 rapid measurements
    for(int i = 0; i < 50 ; i++) {
        uint16_t dist = ToF_ReadDistance(hi2c);

        // Ignore dead reads (0) or massive error spikes
        if(dist > 0 && dist < 4000) {
            total_distance += dist;
            valid_samples++;
        }
        HAL_Delay(70); // Wait for the 50ms timing budget to complete
    }

    // Calculate the physical offset
    if(valid_samples > 0) {
        uint16_t average_measured = total_distance / valid_samples;

        // If the sensor reads 130mm, but the target is 100mm, the offset is -30mm.
        ToF_Offset = exact_target_distance_mm - average_measured;
    }
}

